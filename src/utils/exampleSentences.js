/**
 * 💡 단어와 한글뜻을 분석하여 예문과 번역을 0ms 속도로 반환합니다.
 * 사전 정의 데이터가 없을 경우 하이브리드 비즈니스 템플릿으로 멋지게 생성합니다.
 */
export function getExampleSentence(word, meaning) {
  const cleanWord = word.trim();
  
  if (predefinedExamples[cleanWord]) {
    return predefinedExamples[cleanWord];
  }

  // 한글 뜻에서 쓸데없는 문구 제거
  const cleanMeaning = meaning
    ? meaning.replace(/\s*\(정답은[^)]+\)/g, "").replace(/\[[^\]]+\]/g, "").trim()
    : "학습 단어";

  // 하이브리드 동적 제너레이터 풀
  const templates = [
    {
      sentence: `この「${cleanWord}」という概念を深く理解することが、JLPT N1合格への近道です。`,
      translation: `이 「${cleanMeaning}」이라는 개념을 깊이 이해하는 것이 JLPT N1 합격으로 가는 지름길입니다.`
    },
    {
      sentence: `ビジネスの実務において、「${cleanWord}」に関する知識は極めて重要とされています。`,
      translation: `비즈니스 실무에 있어서, 「${cleanMeaning}」에 관한 지식은 매우 중요하게 여겨집니다.`
    },
    {
      sentence: `現代社会の動向を見ると、「${cleanWord}」の役割が再評価されていることが分かります。`,
      translation: `현대 사회의 동향을 보면, 「${cleanMeaning}」의 역할이 재평가되고 있음을 알 수 있습니다.`
    }
  ];

  // 단어의 글자 길이(해시)를 기준으로 균등하게 3개 템플릿 중 하나를 선택 매칭
  const index = cleanWord.length % templates.length;
  return templates[index];
}
