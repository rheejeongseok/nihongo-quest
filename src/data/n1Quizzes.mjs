export { lexicalRows as n1Lexicon };

function alternatives(rows, index, field, answer) {
  const result = [];
  for (let step = 1; result.length < 3 && step < rows.length; step++) {
    const value = rows[(index + step * 7) % rows.length][field];
    if (value !== answer && !result.includes(value)) result.push(value);
  }
  return result;
}

export function buildN1Quizzes(stageIds) {
  const result = [];
  const add = (id, stage, type, question, word, reading, answer, wrong, hint) => result.push({
    id: `n1-v2-${id}`, stageId: stageIds[stage], quizType: type,
    questionText: `[N1] ${question}`, japaneseWord: word, pronunciation: reading,
    correctAnswer: answer, wrongAnswers: JSON.stringify(wrong), hint
  });
  lexicalRows.forEach(([word, reading, meaning, sentence], index) => {
    const hint = `${word}（${reading}）: ${meaning}`;
    add(`reading-${index}`, 1, 'MULTIPLE_CHOICE', `【漢字読み】「${word}」の読み方を選びなさい。\n${sentence}`, word, reading,
      reading, alternatives(lexicalRows, index, 1, reading), hint);
    add(`context-${index}`, 2, 'MULTIPLE_CHOICE', `【文脈規定】（　）に入る最も適切な語を選びなさい。\n${sentence.replace(word, '（　）')}`,
      sentence.replace(word, '（　）'), '', word, alternatives(lexicalRows, index, 0, word), hint);
    add(`paraphrase-${index}`, 2, 'MULTIPLE_CHOICE', `【言い換え】文中の「${word}」の意味に最も近いものを選びなさい。\n${sentence}`,
      word, reading, meaning, alternatives(lexicalRows, index, 2, meaning), hint);
    add(`wordle-${index}`, 5, 'WORDLE', `【語彙復習】説明に合う${word.length}文字の語を完成させなさい。\n${meaning}`,
      word, reading, word, [], meaning);
  });
  usageRows.forEach(([word, answer, ...wrong], index) => add(`usage-${index}`, 2, 'MULTIPLE_CHOICE',
    `【用法】「${word}」の使い方として最も適切な文を選びなさい。`, word, '', answer, wrong,
    `正しい用法: ${answer}`));
  textGrammarRows.forEach(([text, answer, wrong], index) => add(`text-grammar-${index}`, 3, 'MULTIPLE_CHOICE',
    `【文章の文法】文章のつながりに合うものを選びなさい。\n${text}`, text, '', answer, wrong,
    `文脈に合う表現: ${answer}`));
  grammarRows.forEach(([expression, explanation, distractors, ...sentences], index) => {
    sentences.forEach((segmented, variant) => {
      const sentence = segmented.replaceAll('/', '').replace(/[{}]/g, '');
      const question = segmented.replaceAll('/', '').replace(/\{[^}]+\}/g, '（　）');
      add(`grammar-${index}-${variant}`, 3, 'MULTIPLE_CHOICE', `【文法形式】（　）に入る最も適切な表現を選びなさい。\n${question}`,
        question, '', expression, distractors.split(','), `${expression}: ${explanation}`);
      const pieces = segmented.replace(/[{}]/g, '').split('/');
      add(`assembly-${index}-${variant}`, 5, 'ASSEMBLY', `【文の組み立て】全ての語句を並べ替えて自然な文を作りなさい。\n문법 단서: ${explanation}`,
        sentence, '', sentence, pieces, `${expression}: ${explanation}`);
    });
  });
  listeningRows.forEach(([topic, script, action, reason, gist, wrong], index) => {
    const tasks = [
      ['課題理解', '話を聞いた人は、まず何をしますか。', action],
      ['ポイント理解', 'この対応を取る主な理由は何ですか。', reason],
      ['概要理解', '話し手の考えに最も近いものはどれですか。', gist]
    ];
    tasks.forEach(([type, question, answer], variant) => add(`listening-${index}-${variant}`, 4, 'LISTENING',
      `【${type}】${topic}についての話を聞いて答えなさい。\n${question}`, script, '', answer,
      variant === 1 ? wrong.map(value => `${value}必要があるから`) : variant === 2 ? wrong.map(value => `${value}べきだ`) : wrong,
      `대본: ${script}\n해설: ${answer}`));
  });
  responseRows.forEach(([script, answer, ...wrong], index) => add(`response-${index}`, 4, 'LISTENING',
    '【即時応答】発言を聞いて、最も適切な返答を選びなさい。', script, '', answer, wrong,
    `発言: ${script}\n適切な応答: ${answer}`));
  return result;
}
