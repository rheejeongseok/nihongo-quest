export function addBeginnerVocabulary(add) {
  for (const [difficulty, rows] of Object.entries(levels)) rows.forEach(([word, reading, wrongReading, sentence, meaning, wrongMeaning, hint], index) => {
    const key = `${difficulty.toLowerCase()}${index + 1}`;
    add('VOCAB', key, difficulty, 'reading', 'MULTIPLE_CHOICE', `「${word}」の読み方を選びましょう。\n${sentence}`, word, reading, reading, wrongReading, `「${word}」は「${reading}」と読みます。${hint}`);
    add('VOCAB', key, difficulty, 'context', 'MULTIPLE_CHOICE', `다음 문장에서 「${word}」의 뜻을 고르세요.\n${sentence}`, word, '', meaning, wrongMeaning, hint);
  });
}
