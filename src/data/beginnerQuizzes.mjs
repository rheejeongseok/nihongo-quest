function circularWrong(items, index, selector) {
  return [1, 2, 3].map(offset => selector(items[(index + offset) % items.length]));
}

function quiz(id, stageId, quizType, difficulty, questionText, japaneseWord, pronunciation, correctAnswer, wrongAnswers, hint) {
  return {
    id: `beginner-${id}`,
    stageId,
    quizType,
    questionText: `[BEGINNER-${difficulty}] ${questionText}`,
    japaneseWord,
    pronunciation,
    correctAnswer,
    wrongAnswers: JSON.stringify(wrongAnswers),
    hint
  };
}

export function buildBeginnerQuizzes(stageIds) {
  const result = [];
  const kanaSets = { EASY: HIRAGANA, MEDIUM: KATAKANA };

  Object.entries(kanaSets).forEach(([difficulty, source]) => {
    const items = source.split(',').map(item => item.split(':'));
    items.forEach(([character, reading], index) => {
      result.push(quiz(`1-${difficulty.toLowerCase()}-${index}`, stageIds[1], 'MULTIPLE_CHOICE', difficulty,
        `「${character}」의 올바른 로마자 발음은?`, character, reading, reading,
        circularWrong(items, index, item => item[1]), `${character} = ${reading}`));
    });
  });

  BASIC_KANJI.forEach(([character, reading, meaning], index) => {
    result.push(quiz(`1-hard-${index}`, stageIds[1], 'MULTIPLE_CHOICE', 'HARD',
      `기초 한자 「${character}」의 대표 읽기는?`, character, reading, reading,
      circularWrong(BASIC_KANJI, index, item => item[1]), meaning));
  });

  Object.entries(VOCAB).forEach(([difficulty, items]) => {
    items.forEach(([word, reading, meaning], index) => {
      result.push(quiz(`2-${difficulty.toLowerCase()}-${index}`, stageIds[2], 'MULTIPLE_CHOICE', difficulty,
        `「${word}」의 뜻은 무엇인가요?`, word, reading, meaning,
        circularWrong(items, index, item => item[2]), `${reading} · ${meaning}`));
    });
  });

  Object.entries(GRAMMAR).forEach(([difficulty, items]) => {
    items.forEach(([sentence, answer, wrongs, meaning], index) => {
      result.push(quiz(`3-${difficulty.toLowerCase()}-${index}`, stageIds[3], 'MULTIPLE_CHOICE', difficulty,
        `빈칸에 들어갈 가장 알맞은 표현은? ${sentence}`, sentence.replace('___', answer), sentence, answer, wrongs, meaning));
    });
  });

  Object.entries(LISTENING).forEach(([difficulty, items]) => {
    items.forEach(([sentence, meaning], index) => {
      result.push(quiz(`4-${difficulty.toLowerCase()}-${index}`, stageIds[4], 'LISTENING', difficulty,
        '음성을 듣고 알맞은 뜻을 고르세요.', sentence, sentence, meaning,
        circularWrong(items, index, item => item[1]), meaning));
    });
  });

  Object.entries(WORDLE).forEach(([difficulty, items]) => {
    items.forEach(([word, meaning], index) => {
      result.push(quiz(`5-wordle-${difficulty.toLowerCase()}-${index}`, stageIds[5], 'WORDLE', difficulty,
        `'${meaning}'을 뜻하는 ${word.length}글자 일본어를 완성하세요.`, word, word, word, [], meaning));
    });
  });

  Object.entries(ASSEMBLY).forEach(([difficulty, items]) => {
    items.forEach(([fragments, meaning], index) => {
      const sentence = fragments.join('');
      result.push(quiz(`5-assembly-${difficulty.toLowerCase()}-${index}`, stageIds[5], 'ASSEMBLY', difficulty,
        `단어 카드를 순서대로 조합하세요. 뜻: ${meaning}`, sentence, sentence, sentence, fragments, meaning));
    });
  });

  return result;
}
