export function addQualityVocabulary(add) {
  const errors = new Map(readingErrors.map(([word, values]) => [word, values.split(',')]));
  const readingNotes = new Map([
    ['端緒', '「たんちょ」도 인정되는 관용 읽기입니다. 오독으로 처리하지 않습니다.'],
    ['融通', '사전에는 「ゆずう」라는 다른 읽기도 있습니다. 이 문장에서는 일반적인 「ゆうずう」를 보여 줍니다.']
  ]);
  const indexFor = word => n1Lexicon.findIndex(row => row[0] === word);
  n1Lexicon.forEach(([word, reading, meaning, sentence], index) => {
    const wrong = errors.get(word);
    if (!wrong) throw new Error(`Missing authored reading alternatives: ${word}`);
    if (/\p{Script=Han}/u.test(word)) add(`lex${index}`, 'reading', 1, 'MULTIPLE_CHOICE', `【漢字読み】「${word}」の読み方を選びなさい。\n${sentence}`, word, reading, reading, wrong,
      `「${word}」(${reading}): ${koMeaning(word)}. 단어 전체의 읽기를 확인하세요.${readingNotes.get(word) ? ' ' + readingNotes.get(word) : ''}`);
    add(`lex${index}`, 'wordle', 5, 'WORDLE', `【語彙復習】説明に合う${word.length}文字の語を完成させなさい。\n${meaning}`, word, reading, word, [], `「${word}」(${reading}): ${koMeaning(word)}`);
  });
  const used = new Set();
  semanticRows.forEach(([word, sentence, unused, answer, wrong, reason]) => {
    if (used.has(word)) return;
    used.add(word);
    const entry = n1Lexicon[indexFor(word)];
    add(`lex${indexFor(word)}`, 'paraphrase', 2, 'MULTIPLE_CHOICE', `【言い換え】次の文の「${word}」の意味に最も近いものを選びなさい。\n${entry[3]}`,
      word, entry[1], answer, wrong, reason);
  });
  contextRows.forEach(([word, text, wrong, reason]) => add(`lex${indexFor(word)}`, 'context', 2, 'MULTIPLE_CHOICE',
    `【文脈規定】（　）に入る最も適切な語を選びなさい。\n${text}`, '', '', word, wrong, reason));
  usageRows.forEach(([word, answer, wrong, reason]) => add(`lex${indexFor(word)}`, 'usage', 2, 'MULTIPLE_CHOICE',
    `【用法】「${word}」を適切に使っている文を選びなさい。`, word, '', answer, wrong, reason));
}
