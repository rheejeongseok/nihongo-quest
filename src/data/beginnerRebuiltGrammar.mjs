export function addBeginnerGrammar(add) {
  for (const [difficulty, rows] of Object.entries(levels)) rows.forEach(([segmented, wrong, hint], index) => {
    const answer = segmented.match(/\{([^}]+)\}/)[1];
    const pieces = segmented.replace(/[{}]/g, '').split('/');
    const sentence = pieces.join('');
    const prompt = segmented.replace(`{${answer}}`, '（　）').split('/').join('');
    const key = `${difficulty.toLowerCase()}${index + 1}`;
    add('GRAMMAR', key, difficulty, 'choice', 'MULTIPLE_CHOICE', `빈칸에 알맞은 표현을 고르세요.\n${prompt}`, '', '', answer, wrong, hint);
    add('GRAMMAR', key, difficulty, 'assembly', 'ASSEMBLY', '모든 조각을 사용해 자연스러운 문장을 만드세요.', sentence, '', sentence, pieces, `${hint}\n완성 문장: ${sentence}`);
  });
}
